const fold = (s: string) => s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/ı/g, "i").toLowerCase();

/** Cities whose name or country starts with (or contains) what was typed; names before countries. */
export function searchCities(q: string, limit = 8): City[] {
  const t = fold(q.trim());
  if (!t) return [];
  const starts: City[] = [];
  const contains: City[] = [];
  for (const c of CITIES) {
    const name = fold(c[0]);
    if (name.startsWith(t)) starts.push(c);
    else if (name.includes(t) || fold(c[1]).startsWith(t)) contains.push(c);
  }
  return [...starts, ...contains].slice(0, limit);
}

